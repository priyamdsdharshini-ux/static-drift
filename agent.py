import re

from langchain.agents import create_agent

import gradio as gr

from llm import create_llm
from shared_tools import search_reference, triage_symptom, specialist_finder
from system_prompts import SYSTEM_PROMPT
from multilingual import (LANGS, BY_CODE, DISCLAIMERS, detect_language, speech_to_text,
                          translate, strip_markdown, text_to_speech)

from dotenv import load_dotenv

load_dotenv()

tools = [search_reference, triage_symptom, specialist_finder]

llm = create_llm()

health_agent = create_agent(
    model=llm,
    tools=tools,
    system_prompt=SYSTEM_PROMPT
)

def ask_english(history_en: list, text_en: str) -> str:
    """The agent always reads and writes English, so the triage rules stay deterministic."""
    messages = history_en[-6:] + [{"role": "user", "content": text_en}]
    response = health_agent.invoke({"messages": messages})
    answer = response["messages"][-1].content
    return re.sub(r"<think>.*?</think>", "", answer, flags=re.S).strip()

def handle(audio, text, lang_choice, speak, chat, history_en):
    forced = None if lang_choice == "Auto-detect" else LANGS[lang_choice][0]

    # 1. Voice or text in, in any language
    if audio:
        heard, code = speech_to_text(audio, forced)
    else:
        heard = (text or "").strip()
        code = forced or (detect_language(heard) if heard else "en")

    if not heard:
        return chat, history_en, None, "Nothing heard. Please try again.", "", None, ""

    lang_name = BY_CODE.get(code, "English")
    nllb = LANGS[lang_name][1]

    # 2. Native language -> English -> agent -> native language
    text_en = translate(heard, nllb, "eng_Latn")
    answer_en = ask_english(history_en, text_en)
    answer_native = translate(strip_markdown(answer_en), "eng_Latn", nllb)

    # 3. Disclaimer is fixed text added in code, never generated by the model
    disclaimer = DISCLAIMERS.get(code) or translate(DISCLAIMERS["en"], "eng_Latn", nllb)

    chat = chat + [
        {"role": "user", "content": heard},
        {"role": "assistant", "content": f"{answer_native}\n\n---\n⚠️ {disclaimer}"},
    ]
    history_en = history_en + [
        {"role": "user", "content": text_en},
        {"role": "assistant", "content": answer_en},
    ]

    # 4. Spoken reply in the user's language
    voice = text_to_speech(f"{answer_native}. {disclaimer}", code) if speak else None

    understood = f"Language: {lang_name}\nHeard: {heard}\nEnglish: {text_en}"
    return chat, history_en, voice, understood, answer_en, None, ""

def deploy_agent():
    with gr.Blocks(title="Patient Health Assistant") as iface:
        gr.Markdown("# 🩺 Patient Health Voice Assistant")
        gr.Markdown(
            "⚠️ **Not a substitute for professional medical advice.** Speak or type in your own language. "
            "In an emergency, call your local emergency number."
        )

        with gr.Row():
            lang = gr.Dropdown(["Auto-detect"] + list(LANGS), value="Auto-detect", label="Language")
            speak = gr.Checkbox(value=True, label="Speak the reply")

        chatbot = gr.Chatbot( height=380)
        state_en = gr.State([])

        mic = gr.Audio(sources=["microphone"], type="filepath", label="🎤 Speak your question")
        box = gr.Textbox(label="Or type here", placeholder="e.g. मुझे तीन दिन से बुखार है / What is dengue?")
        send = gr.Button("Send", variant="primary")
        voice_out = gr.Audio(label="Spoken reply", autoplay=True)

        with gr.Accordion("What the assistant understood (check for translation errors)", open=False):
            understood = gr.Textbox(label="Heard and translated", lines=3)
            answer_en = gr.Textbox(label="English answer", lines=6)

        inputs = [mic, box, lang, speak, chatbot, state_en]
        outputs = [chatbot, state_en, voice_out, understood, answer_en, mic, box]
        send.click(handle, inputs, outputs)
        box.submit(handle, inputs, outputs)
        mic.stop_recording(handle, inputs, outputs)

    iface.launch()

if __name__ == "__main__":
    deploy_agent()
